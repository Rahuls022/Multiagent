import asyncio
import sys
import unittest
from pathlib import Path

backend_dir = str(Path(__file__).resolve().parent.parent)
if backend_dir not in sys.path:
    sys.path.insert(0, backend_dir)

from app.agents.coding_agent import CodingAgent
from app.agents.planning_agent import PlanningAgent


class FakeNvidiaClient:
    is_configured = True

    async def create_json(self, **kwargs):
        return {"summary": "Generated by NVIDIA", "prompt": kwargs["user_prompt"]}


class NvidiaAgentTests(unittest.TestCase):
    def test_planning_agent_uses_configured_nvidia_client(self):
        output = asyncio.run(PlanningAgent(FakeNvidiaClient()).execute({"request": "Build a portal"}, {}))
        self.assertEqual(output["summary"], "Generated by NVIDIA")

    def test_coding_agent_uses_configured_nvidia_client(self):
        context = {"Planning Agent": {"output": {"summary": "A plan"}}}
        output = asyncio.run(CodingAgent(FakeNvidiaClient()).execute({"request": "Build a portal"}, context))
        self.assertEqual(output["summary"], "Generated by NVIDIA")


if __name__ == "__main__":
    unittest.main()
